"""Build board-sized LVGL assets from the existing Mumu portrait catalog."""

import argparse
from hashlib import sha256
from pathlib import Path
import json
import re
import struct
import sys

from PIL import Image


PORTRAIT_SIZE = (260, 260)
# One portrait per mood. Choose distinct expressions that read on the 3.5-inch panel.
SELECTION = (
    ("neutral", "Calm", "neutral_default"),
    ("happy", "Happy", "happy_severe"),
    ("excited", "Excited", "excited_moderate"),
    ("shy", "Shy", "shy_moderate"),
    ("confused", "Puzzled", "confused_moderate"),
    ("sad", "Sad", "sad_severe"),
    ("angry", "Angry", "angry_severe"),
)


def pack_portrait(path, background):
    with Image.open(path) as source:
        rgba = source.convert("RGBA")
    rgba.thumbnail(PORTRAIT_SIZE, Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", PORTRAIT_SIZE, (*background, 255))
    canvas.alpha_composite(rgba, ((canvas.width - rgba.width) // 2, canvas.height - rgba.height))
    rgb = canvas.convert("RGB").tobytes()
    pixels = bytearray(2 * canvas.width * canvas.height)
    # LVGL uses RGB565 with LV_COLOR_16_SWAP=1 for this panel.
    for offset in range(0, len(rgb), 3):
        r, g, b = rgb[offset:offset + 3]
        pixel = (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)
        index = offset // 3 * 2
        pixels[index] = pixel >> 8
        pixels[index + 1] = pixel & 255
    return pixels


ASSET_MAGIC = 0x31415347  # "GSA1" little-endian
ASSET_HEADER = "<IHHHHI"  # magic, version, count, width, height, reserved
ASSET_ENTRY = 24          # char name[16], u32 offset, u32 length


def generate_external(role, sketch, blob):
    """外部资产模式：像素写进 blob（放进 ffat 资产区），固件启动时读入 PSRAM。

    与内嵌模式共用同一套 SELECTION 与解码逻辑，只是不生成 C 像素数组。
    """
    role = role.resolve()
    catalog_path = role / "portrait_catalog.json"
    catalog_data = catalog_path.read_bytes()
    catalog = json.loads(catalog_data)
    if catalog.get("schema_version") != 1:
        raise ValueError("Expected a version 1 Mumu portrait catalog.")
    assets = {entry["id"]: entry for entry in catalog["assets"]}

    header = (sketch / "portrait_assets.h").read_text(encoding="utf-8")
    color = re.search(r"\bportrait_background = 0x([0-9A-Fa-f]{6});", header)
    if color is None:
        raise ValueError("Missing portrait_background color in portrait_assets.h.")
    background = bytes.fromhex(color[1])

    manifest = {
        "catalog_sha256": sha256(catalog_data).hexdigest(),
        "size": PORTRAIT_SIZE,
        "format": "RGB565 big endian",
        "background": "#" + background.hex(),
        "mode": "external-blob",
        "blob_bytes": 0,
        "portraits": [],
    }
    packed = []
    for mood, label, asset_id in SELECTION:
        asset = assets[asset_id]
        if asset.get("cluster") != mood or asset.get("kind") != "image":
            raise ValueError(f"Expected a {mood} portrait at {asset_id}.")
        path = (role / asset["path"]).resolve()
        if not path.is_relative_to(role) or path.suffix.lower() != ".png":
            raise ValueError(f"Invalid local PNG path for {asset_id}.")
        pixels = pack_portrait(path, background)
        packed.append((mood, label, pixels))
        manifest["portraits"].append({
            "mood": mood,
            "label": label,
            "asset_id": asset_id,
            "source": path.relative_to(role).as_posix(),
            "source_sha256": sha256(path.read_bytes()).hexdigest(),
            "pixel_sha256": sha256(bytes(pixels)).hexdigest(),
        })

    offset = struct.calcsize(ASSET_HEADER) + ASSET_ENTRY * len(packed)
    index = bytearray()
    data = bytearray()
    for mood, _label, pixels in packed:
        index += struct.pack("<16sII", mood.encode("ascii"), offset + len(data), len(pixels))
        data += bytes(pixels)
    blob_data = (
        struct.pack(ASSET_HEADER, ASSET_MAGIC, 1, len(packed),
                    PORTRAIT_SIZE[0], PORTRAIT_SIZE[1], 0)
        + bytes(index) + bytes(data)
    )
    blob = Path(blob)
    blob.parent.mkdir(parents=True, exist_ok=True)
    blob.write_bytes(blob_data)
    manifest["blob_bytes"] = len(blob_data)

    source = [
        '// Generated by pack-portraits.py in external asset mode.',
        '// Pixels live in the ffat asset blob; firmware loads them into PSRAM at boot.',
        '#include "portrait_assets.h"',
        '',
        'Portrait portraits[] = {',
    ]
    source.extend(f'    {{"{mood}", "{label}", nullptr}},' for mood, label, _ in SELECTION)
    source.extend(('};', 'const size_t portrait_count = sizeof(portraits) / sizeof(portraits[0]);', ''))
    (sketch / "portrait_assets.cpp").write_text("\n".join(source), encoding="utf-8")
    (sketch.parent / "mumu-assets.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Packed {len(SELECTION)} Mumu portraits into {blob.name} ({len(blob_data)} bytes).")


def generate(role, sketch):
    role = role.resolve()
    catalog_path = role / "portrait_catalog.json"
    catalog_data = catalog_path.read_bytes()
    catalog = json.loads(catalog_data)
    if catalog.get("schema_version") != 1:
        raise ValueError("Expected a version 1 Mumu portrait catalog.")
    assets = {entry["id"]: entry for entry in catalog["assets"]}

    header = (sketch / "portrait_assets.h").read_text(encoding="utf-8")
    color = re.search(r"\bportrait_background = 0x([0-9A-Fa-f]{6});", header)
    if color is None:
        raise ValueError("Missing portrait_background color in portrait_assets.h.")
    background = bytes.fromhex(color[1])
    images = sketch / "portraits"
    images.mkdir(exist_ok=True)

    source = [
        '// Generated by pack-portraits.py from the Mumu role pack.',
        '#include "portrait_assets.h"',
        '#if LV_COLOR_DEPTH != 16 || LV_COLOR_16_SWAP != 1',
        '#error "Mumu portrait assets require byte-swapped RGB565"',
        '#endif',
        '',
        'namespace {',
        'lv_img_dsc_t describe(const uint8_t *pixels, uint32_t size) {',
        '    lv_img_dsc_t image{};',
        '    image.header.cf = LV_IMG_CF_TRUE_COLOR;',
        f'    image.header.w = {PORTRAIT_SIZE[0]};',
        f'    image.header.h = {PORTRAIT_SIZE[1]};',
        '    image.data_size = size;',
        '    image.data = pixels;',
        '    return image;',
        '}',
    ]
    manifest = {
        "catalog_sha256": sha256(catalog_data).hexdigest(),
        "size": PORTRAIT_SIZE,
        "format": "RGB565 big endian",
        "background": "#" + background.hex(),
        "portraits": [],
    }
    for mood, label, asset_id in SELECTION:
        asset = assets[asset_id]
        if asset.get("cluster") != mood or asset.get("kind") != "image":
            raise ValueError(f"Expected a {mood} portrait at {asset_id}.")
        path = (role / asset["path"]).resolve()
        if not path.is_relative_to(role) or path.suffix.lower() != ".png":
            raise ValueError(f"Invalid local PNG path for {asset_id}.")
        pixels = pack_portrait(path, background)
        (images / f"{mood}.inc").write_text(
            "\n".join("    " + ", ".join(f"0x{b:02x}" for b in pixels[i:i + 16]) + ","
                      for i in range(0, len(pixels), 16)) + "\n",
            encoding="utf-8",
        )
        source.extend((
            f'alignas(4) const uint8_t {mood}_pixels[] = {{',
            f'#include "portraits/{mood}.inc"',
            '};',
            f'const lv_img_dsc_t {mood}_image = describe({mood}_pixels, sizeof({mood}_pixels));',
        ))
        manifest["portraits"].append({
            "mood": mood,
            "label": label,
            "asset_id": asset_id,
            "source": path.relative_to(role).as_posix(),
            "source_sha256": sha256(path.read_bytes()).hexdigest(),
            "pixel_sha256": sha256(pixels).hexdigest(),
        })

    source.extend(('}  // namespace', '', 'const Portrait portraits[] = {'))
    source.extend(f'    {{"{mood}", "{label}", &{mood}_image}},' for mood, label, _ in SELECTION)
    source.extend(('};', 'const size_t portrait_count = sizeof(portraits) / sizeof(portraits[0]);', ''))
    (sketch / "portrait_assets.cpp").write_text("\n".join(source), encoding="utf-8")
    (sketch.parent / "mumu-assets.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Packed {len(SELECTION)} Mumu portraits at {PORTRAIT_SIZE[0]} x {PORTRAIT_SIZE[1]}.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("role", type=Path, help="Directory containing Mumu's portrait_catalog.json")
    parser.add_argument("sketch", type=Path, help="Staged Arduino sketch directory")
    parser.add_argument("--blob", type=Path,
                        help="External asset mode: write pixels to this blob instead of compiling them in")
    args = parser.parse_args()
    try:
        if args.blob is not None:
            generate_external(args.role, args.sketch, args.blob)
        else:
            generate(args.role, args.sketch)
    except (KeyError, OSError, ValueError) as error:
        sys.exit(f"Cannot pack Mumu portraits: {error}")


if __name__ == "__main__":
    main()
